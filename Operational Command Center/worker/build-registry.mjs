// Generates src/registry.mjs from every .claude/skills/<skill>/scripts/runner.mjs in the repo.
// Runs before `wrangler deploy` (see package.json and the GitHub workflow).
import { readdirSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const skillsDir = resolve(repo, ".claude", "skills");
const out = resolve(here, "src", "registry.mjs");

const found = [];
for (const name of readdirSync(skillsDir).sort()) {
  const runner = resolve(skillsDir, name, "scripts", "runner.mjs");
  if (existsSync(runner)) found.push(name);
}

const lines = ["// Generated by build-registry.mjs - do not edit. One entry per skill folder with scripts/runner.mjs."];
found.forEach((name, i) => lines.push(`import { skill as s${i} } from "../../../.claude/skills/${name}/scripts/runner.mjs";`));
lines.push("");
lines.push("export const SKILLS = [" + found.map((_, i) => "s" + i).join(", ") + "];");
lines.push("export const SOURCES = " + JSON.stringify(Object.fromEntries(found.map((n) => [n, ".claude/skills/" + n + "/SKILL.md"]))) + ";");
lines.push("");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log("registry: " + (found.length ? found.join(", ") : "no skills") + " -> " + out);
