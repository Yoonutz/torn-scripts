// Generates src/registry.mjs from every .claude/skills/<skill>/scripts/runner.mjs in the repo.
// Runs before `wrangler deploy` (wrangler.toml [build]). Each entry carries its own folder and
// its SKILL.md text, so the Worker never fetches it at run time. Bad skills fail the build.
import { readdirSync, existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const skillsDir = resolve(repo, ".claude", "skills");
const out = resolve(here, "src", "registry.mjs");
const ACCESS = ["public", "minimal", "limited", "full"];
const AI = ["deliver", "raw"];

const found = [];
for (const name of readdirSync(skillsDir).sort()) {
  const runner = resolve(skillsDir, name, "scripts", "runner.mjs");
  if (existsSync(runner)) found.push(name);
}

// Load each runner once to check its export before anything deploys.
const errors = [];
const ids = {};
for (const name of found) {
  const where = ".claude/skills/" + name + "/scripts/runner.mjs";
  let skill;
  try {
    skill = (await import(pathToFileURL(resolve(skillsDir, name, "scripts", "runner.mjs")).href)).skill;
  } catch (e) {
    errors.push(where + ": cannot be imported (" + e.message + ")");
    continue;
  }
  if (!skill || typeof skill !== "object") errors.push(where + ": no `export const skill`");
  else {
    if (!/^[a-z0-9_-]+$/.test(skill.id || "")) errors.push(where + ": id must be lowercase letters, digits, - or _");
    if (ids[skill.id]) errors.push(where + ": id \"" + skill.id + "\" already used by " + ids[skill.id]);
    ids[skill.id] = where;
    if (!skill.label) errors.push(where + ": label missing");
    if (typeof skill.run !== "function") errors.push(where + ": run(ctx) missing");
    if (skill.access && !ACCESS.includes(skill.access)) errors.push(where + ": access must be one of " + ACCESS.join(", "));
    if (skill.ai && !AI.includes(skill.ai)) errors.push(where + ": ai must be one of " + AI.join(", ") + " (or add prompt())");
    if (skill.prompt && typeof skill.prompt !== "function") errors.push(where + ": prompt must be a function");
  }
  if (!existsSync(resolve(skillsDir, name, "SKILL.md"))) errors.push(".claude/skills/" + name + ": SKILL.md missing");
}
if (errors.length) {
  console.error("registry: build stopped\n- " + errors.join("\n- "));
  process.exit(1);
}

const lines = ["// Generated by build-registry.mjs - do not edit. One entry per skill folder with scripts/runner.mjs."];
found.forEach((name, i) => lines.push(`import { skill as s${i} } from "../../../.claude/skills/${name}/scripts/runner.mjs";`));
lines.push("");
lines.push("export const REGISTRY = [");
found.forEach((name, i) => {
  const md = ".claude/skills/" + name + "/SKILL.md";
  lines.push(`  { folder: ${JSON.stringify(name)}, md: ${JSON.stringify(md)}, text: ${JSON.stringify(readFileSync(resolve(repo, md), "utf8"))}, skill: s${i} },`);
});
lines.push("];");
lines.push("");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log("registry: " + (found.length ? found.join(", ") : "no skills") + " -> " + out);
